// facturXDataModelRules evaluates the profile's data model over the document and
// returns its findings, in document order.
//
// It is a no-op for any root but CrossIndustryInvoice, and for a Profile with no
// data model — neither of which can happen on the path Validate takes, and both of
// which are the safe answer if it ever does.
func facturXDataModelRules(r *run, root *ciiNode, profile Profile) []Violation {
	rules := facturXDataModel[profile]
	if root == nil || root.name != "CrossIndustryInvoice" || len(rules) == 0 {
		return nil
	}
	ix := fxDMIndexes()[profile]
	if ix == nil {
		return nil
	}
	top := ix.kids[root.name]
	if top == nil {
		return nil
	}
	e := &fxDMEval{run: r, rules: rules}
	e.chain = append(e.chain, root)
	e.walk(root, top)
	return e.out
}

// fxDMEval carries the state of one document's walk: the ancestor chain, so that
// a predicate's `..` steps and absolute paths can be resolved, and the findings.
type fxDMEval struct {
	run   *run
	rules []fxDMRule
	chain []*ciiNode
	out   []Violation
	// nodes counts the context nodes visited, so the cancellation poll is not one
	// channel receive per element of a large document.
	nodes   int
	stopped bool
}

// fxDMCancelNodes is how many context nodes the walk covers between cancellation
// polls, for the reason parseCII gives for cancelParseTokens.
const fxDMCancelNodes = 512

func (e *fxDMEval) walk(n *ciiNode, ix *fxDMIndex) {
	if e.stopped {
		return
	}
	e.nodes++
	if e.nodes%fxDMCancelNodes == 0 && e.run.stopped() {
		e.stopped = true
		return
	}
	if len(ix.rules) > 0 {
		e.apply(ix.rules)
	}
	if ix.kids == nil {
		return
	}
	for _, c := range n.children {
		next := ix.kids[c.name]
		if next == nil {
			continue
		}
		e.chain = append(e.chain, c)
		e.walk(c, next)
		e.chain = e.chain[:len(e.chain)-1]
		if e.stopped {
			return
		}
	}
}

// apply runs the rules whose context step names end at the current node, honouring
// ISO Schematron's first-match-per-pattern.
func (e *fxDMEval) apply(candidates []int) {
	// A node reaches at most a handful of competing rules — three, at the widest
	// point of these files — so the set of patterns already matched is a short
	// array rather than a map, and the whole of apply allocates nothing.
	var seenArr [8]int
	seen := seenArr[:0]
	node := e.chain[len(e.chain)-1]
	for _, ri := range candidates {
		r := &e.rules[ri]
		claimed := false
		for _, p := range seen {
			if p == r.pattern {
				claimed = true
				break
			}
		}
		if claimed {
			continue
		}
		if !e.stepsMatch(r.steps) {
			continue
		}
		// append grows past the array only if more patterns compete at one node
		// than these files ever put there, which costs an allocation and stays
		// correct; dropping the constraint instead would let a shadowed rule
		// report, which is C42.
		seen = append(seen, r.pattern)
		for i := range r.asserts {
			e.assert(node, &r.asserts[i])
		}
	}
}

// stepsMatch checks the predicates of a context whose step names have already
// been matched by the trie. Step i is evaluated against chain[i], with chain[:i+1]
// as its ancestor context.
func (e *fxDMEval) stepsMatch(steps []fxDMStep) bool {
	if len(steps) != len(e.chain) {
		return false
	}
	for i := range steps {
		if len(steps[i].pred.terms) == 0 {
			continue
		}
		if !e.pred(steps[i].pred, e.chain[:i+1]) {
			return false
		}
	}
	return true
}

// assert evaluates one assertion at the context node and appends its finding if it
// reports.
func (e *fxDMEval) assert(node *ciiNode, a *fxDMAssert) {
	switch a.op {
	case fxDMCountEQ, fxDMCountLE, fxDMCountGE:
		n := 0
		for _, c := range node.children {
			if c.name != a.child.name {
				continue
			}
			if len(a.child.pred.terms) > 0 {
				e.chain = append(e.chain, c)
				ok := e.pred(a.child.pred, e.chain)
				e.chain = e.chain[:len(e.chain)-1]
				if !ok {
					continue
				}
			}
			n++
		}
		switch a.op {
		case fxDMCountEQ:
			if n == a.bound {
				return
			}
		case fxDMCountLE:
			if n <= a.bound {
				return
			}
		case fxDMCountGE:
			if n >= a.bound {
				return
			}
		}
	case fxDMUnused:
		// `report true()`: the context node existing is the finding.
	case fxDMAttrRequired:
		if node.hasAttr(a.attr) {
			return
		}
	case fxDMAttrForbidden:
		if !node.hasAttr(a.attr) {
			return
		}
	case fxDMCode:
		v, present := e.codeValue(node, a.value)
		if !present || v == "" {
			// FNFE's own string-length($v)=0 disjunct. An absent attribute has
			// string-length 0 too, which is why "not present" and "empty" are one
			// answer here: the cardinality and attribute shapes are what decide
			// whether it should have been there.
			return
		}
		if fxDMInList(a.list, v) {
			return
		}
	default:
		// Unreachable: fxDMCheckTable rejects an unknown op when the index is
		// built, before any document is read. The case is here rather than
		// omitted because a switch that falls through to nothing is exactly the
		// C41 shape — an assertion that is present, reachable and inert.
		panic("formalis: unreachable: " + a.key + " has op " + a.test)
	}
	e.out = append(e.out, Violation{
		Source:   SourceFacturX,
		Rule:     a.key,
		Severity: SeverityFatal,
		Message:  a.msg + " (" + a.test + " at " + e.contextPath() + ")",
	})
}

// contextPath renders the path of the node the assertion was evaluated at, which
// is what makes a finding whose identifier is synthetic actionable: the message
// names the element, the test names the constraint, and this names the place.
func (e *fxDMEval) contextPath() string {
	var b strings.Builder
	for _, n := range e.chain {
		b.WriteByte('/')
		b.WriteString(n.name)
	}
	return b.String()
}

// codeValue reads the value a code-list assertion looks up: the context node's
// string value, or one of its attributes.
func (e *fxDMEval) codeValue(node *ciiNode, p fxDMPath) (string, bool) {
	if p.attr != "" {
		v, ok := node.attrs[p.attr]
		return v, ok
	}
	return fxDMStringValue(node), true
}

// fxDMInList reports whether the code list holds v. The lists are emitted sorted
// and deduplicated, so this is a binary search over a slice the linker put in the
// binary — nothing is built at load.
func fxDMInList(list int, v string) bool {
	if list < 0 || list >= len(facturXCodeLists) {
		return false
	}
	l := facturXCodeLists[list]
	i := sort.SearchStrings(l, v)
	return i < len(l) && l[i] == v
}

// ---------------------------------------------------------------------------
// Paths and predicates
// ---------------------------------------------------------------------------

// pred reports whether every term holds at the node at the end of chain.
func (e *fxDMEval) pred(p fxDMPred, chain []*ciiNode) bool {
	for i := range p.terms {
		if !e.term(&p.terms[i], chain) {
			return false
		}
	}
	return true
}

func (e *fxDMEval) term(t *fxDMTerm, chain []*ciiNode) bool {
	v := e.termValue(t, chain)
	if t.negs&1 == 1 {
		return !v
	}
	return v
}

func (e *fxDMEval) termValue(t *fxDMTerm, chain []*ciiNode) bool {
	if !t.eq {
		// A bare path in boolean position: XPath's existence test.
		found := false
		e.each(t.left, chain, func(string) bool { found = true; return true })
		return found
	}
	if t.isLit {
		found := false
		e.each(t.left, chain, func(s string) bool {
			if s == t.lit {
				found = true
				return true
			}
			return false
		})
		return found
	}
	// A general comparison between two node sets: true when some pair is equal.
	// The right side of every one of these selects at most two nodes, so the
	// nested iteration is cheaper than materialising either side.
	found := false
	e.each(t.left, chain, func(l string) bool {
		e.each(t.right, chain, func(rv string) bool {
			if l == rv {
				found = true
				return true
			}
			return false
		})
		return found
	})
	return found
}

// each calls fn with the string value of every node the path selects, stopping
// when fn returns true. It allocates nothing: the selection is a walk, not a
// materialised node set.
func (e *fxDMEval) each(p fxDMPath, chain []*ciiNode, fn func(string) bool) {
	var start *ciiNode
	switch {
	case p.abs:
		start = chain[0]
		// An absolute path names the document element as its first step, which is
		// the node chain[0] already is; the step is consumed here so the walk
		// below is over children throughout.
		if len(p.steps) == 0 {
			return
		}
		if p.steps[0] != start.name {
			return
		}
		e.descend(start, p.steps[1:], p.attr, fn)
		return
	default:
		i := len(chain) - 1 - p.up
		if i < 0 {
			// A parent step above the document element selects nothing, which is
			// what XPath says: the root node has no element parent.
			return
		}
		start = chain[i]
	}
	e.descend(start, p.steps, p.attr, fn)
}

// descend walks the remaining element steps from n and yields the string value of
// each node the path ends at.
func (e *fxDMEval) descend(n *ciiNode, steps []string, attr string, fn func(string) bool) {
	if len(steps) == 0 {
		if attr != "" {
			if v, ok := n.attrs[attr]; ok {
				fn(v)
			}
			return
		}
		fn(fxDMStringValue(n))
		return
	}
	for _, c := range n.children {
		if c.name == steps[0] {
			e.descend(c, steps[1:], attr, fn)
		}
	}
}

// fxDMStringValue is XPath's string-value of an element: the concatenation of all
// its descendant character data.
//
// Every element these assertions read is a leaf, so the fast path is the only one
// that runs in practice; the general case is here because "every element is a
// leaf" is a property of the documents, not of the rule, and a code value read
// from an element that turned out to have children would otherwise silently be
// the whitespace between them.
func fxDMStringValue(n *ciiNode) string {
	if len(n.children) == 0 {
		return n.text
	}
	var b strings.Builder
	fxDMAppendText(&b, n)
	return b.String()
}

func fxDMAppendText(b *strings.Builder, n *ciiNode) {
	b.WriteString(n.text)
	for _, c := range n.children {
		fxDMAppendText(b, c)
	}
}
