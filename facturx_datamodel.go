// The evaluator for the Factur-X profile data model.
//
// # What this is for
//
// EN 16931 is a semantic model plus, per syntax, a normative binding. CEN's CII
// binding is EN16931-CII-syntax.sch, and Factur-X does not adopt it: each of the
// five profile Schematrons carries a binding of its own, generated from that
// profile's element table, one assertion per element. 2,159 assertions in all —
// 48 in MINIMUM, 196 in BASIC WL, 262 in BASIC, 412 in EN 16931 and 1,241 in
// EXTENDED — and none of them carries an identifier, because FNFE names a rule by
// an "[ID]-" prefix on its message text and these have none.
//
// They decide exactly the questions CEN's CII-SR-*/CII-DT-* rules decide, and
// give per-profile answers. CEN's CII-DT-027 forbids ram:FormattedIssueDateTime
// on every document reference but the preceding invoice; the EN 16931 profile
// forbids it on ram:AdditionalReferencedDocument by type code; EXTENDED permits
// it there. Substituting CEN's binding for this layer is issue #56, and PR 57
// stopped doing that. This file is the other half: evaluating what Factur-X
// publishes in its place, so that a Factur-X verdict rests on Factur-X's rules
// rather than on a gap.
//
// # The six shapes
//
// The table is generated by internal/gen/facturx, which refuses — loudly, naming
// the profile, the context and the XPath — anything outside these six:
//
//	count(X)=n / <=n / >=n   "Element 'X' must occur exactly n times"
//	report true()            "Element 'X' is marked as not used in the given context"
//	assert @a                "Attribute '@a' is required in this context"
//	report @a                "Attribute @a' marked as not used in the given context"
//	assert string-length($v)=0 or document('..._codedb.xml')/codedb/cl[@id=n]/enumeration[@value=$v]
//	                         "Value of 'X' is not allowed"
//
// The last of those reads a code database FNFE ships beside the .sch. PR 57
// recorded it as not separately fetchable; it is — ZUGFeRD/mustangproject carries
// FACTUR-X_<PROFILE>_codedb.xml in the same directory as the five .sch, which is
// where `make facturx-schematron` already fetches from, so all 366 code-list
// assertions are evaluated rather than named as a gap.
//
// # The synthetic identifier
//
// These assertions have no identifier, and Violation.Rule cannot be empty: a
// finding a caller cannot name is a finding a caller cannot suppress, aggregate or
// look up. So each is keyed
//
//	FX-DM-<PROFILE>-<NNNN>
//
// where NNNN is the assertion's 1-based position in document order among that
// profile's data-model assertions — FX-DM-EXTENDED-0413, FX-DM-MINIMUM-0007. The
// key is minted by this package rather than quoted from the artefact, and it is
// deterministic: regenerating from the same five files reproduces it exactly.
//
// It is positional, so a future FNFE revision that inserts an assertion shifts
// every key after it. That is a real cost and it is the reason the key is
// documented here rather than buried: it is not a stable external name across
// artefact versions, and a caller pinning one should pin the version of the
// Schematron too. The alternative — a hash of the context and test — is stable
// under insertion and unreadable, and it would still change whenever FNFE edited
// the expression, which is the case that actually matters. Either way the drift is
// visible rather than silent: TestFacturXDataModelMatchesTheArtefact re-derives
// the whole set from the vendored files and fails on any difference in either
// direction, so a shifted key cannot reach a release without regenerating.
//
// # Severity
//
// Every one of the 2,159 is unflagged in the artefact, and within these files the
// absence of a flag is evidence rather than a default: FNFE flags 21 assertions
// warning and leaves the rest unset. So they are fatal, which is the same reading
// facturx.go makes of an unflagged BR-FXEXT-* rule. The generator refuses to emit
// a data-model assertion that carries a flag, because that would be a severity it
// would have to decide.
//
// # Rule order
//
// Under ISO Schematron a node goes to the first matching rule of a pattern and to
// no other. Every context here is an absolute path from the document element, so
// two rules can compete only when their step names coincide and their predicates
// differ — which happens 30 times across the five files, always between the
// variants of one element (`[ram:ID/@schemeID="VA"]`, `[ram:ID/@schemeID="FC"]`,
// `[not(...VA) and not(...FC)]`). fxDMEvaluate takes the first match per pattern,
// which is the rule as published. This is the fifth place ISO rule ordering has
// decided something in this package; C42 is what it costs to get it wrong.

// fxDMKeyPrefix is what every data-model finding's Rule starts with. It is the
// one place the synthetic-identifier convention is written down, so that a test
// or a caller separating these findings from the ones an authority named does not
// have to spell the prefix out.
const fxDMKeyPrefix = "FX-DM-"

// fxIsDataModelRule reports whether a rule identifier is one this package minted
// for an assertion the artefact left unnamed.
func fxIsDataModelRule(rule string) bool { return strings.HasPrefix(rule, fxDMKeyPrefix) }

// fxDMOp is the shape of one data-model assertion. The generator emits these
// names rather than their numeric values, so reordering them here is a compile
// error in the table rather than a silent renumbering of 2,159 assertions.
type fxDMOp uint8

const (
	// fxDMCountEQ, fxDMCountLE and fxDMCountGE are count(child)=n, <=n and >=n.
	fxDMCountEQ fxDMOp = iota
	fxDMCountLE
	fxDMCountGE
	// fxDMUnused is `report true()`: the element exists in CII and this profile
	// does not use it, so its presence is the finding.
	fxDMUnused
	// fxDMAttrRequired is `assert @a` and fxDMAttrForbidden is `report @a`. Both
	// are existence tests on an attribute node, so an attribute written empty is
	// present — which is what XPath says and what FNFE's own processor does.
	fxDMAttrRequired
	fxDMAttrForbidden
	// fxDMCode is the code-database lookup. An empty value passes, which is
	// FNFE's own string-length($v)=0 disjunct and not a leniency added here.
	fxDMCode
)

// fxDMPath is a location path inside a predicate, as the artefact writes them:
// absolute from the document element, or relative to the context node with some
// number of parent steps, ending optionally in an attribute.
//
// steps hold local names. The artefact writes qualified ones (ram:, rsm:, udt:)
// and parseCII keys the tree on local names; TestFacturXDataModelNamesAreUnambiguous
// asserts that no two qualified names anywhere in the five files share a local
// name, so nothing is lost by the reduction.
type fxDMPath struct {
	abs   bool
	up    int
	steps []string
	attr  string
}

// fxDMTerm is one conjunct of a predicate: an existence test, or a general
// comparison against a literal or another path, under negs not() wrappers.
//
// The comparison is XPath's *general* comparison, which is why left and right are
// node sets rather than values: `@currencyID=../../ram:InvoiceCurrencyCode` is
// true when some selected attribute equals some selected element's string value,
// and false — not an error, and not vacuously true — when either side selects
// nothing. Reading it as a value comparison would make
// `[not(@currencyID=../../ram:InvoiceCurrencyCode)]` claim every amount in a
// document that declares no invoice currency.
type fxDMTerm struct {
	negs  int
	left  fxDMPath
	eq    bool
	isLit bool
	lit   string
	right fxDMPath
}

// fxDMPred is a conjunction of terms, which is the only connective the artefact
// uses inside a predicate. The zero value is "no predicate", which matches every
// node.
type fxDMPred struct {
	terms []fxDMTerm
}

// fxDMStep is one step of a context path, or the argument of a count().
type fxDMStep struct {
	name string
	pred fxDMPred
}

// fxDMAssert is one assertion of the data model. test and msg are FNFE's own
// XPath and message text, whitespace-normalised and otherwise verbatim, so the
// generated table reads against the Schematron line by line and the fidelity test
// is a string comparison rather than an argument about a transformation.
type fxDMAssert struct {
	key string
	op  fxDMOp

	child fxDMStep // the counted element, for the three cardinality ops
	bound int      // the cardinality bound
	attr  string   // the attribute, for the two attribute ops
	value fxDMPath // the <let> value the code lookup reads: empty means the context item
	list  int      // index into facturXCodeLists
	clID  int      // FNFE's cl/@id, so the row can be found in the code database

	test string
	msg  string
}

// fxDMRule is one <rule> of a pattern that carries data-model assertions. A rule
// with no assertions is still here: under ISO Schematron it claims its nodes away
// from every rule below it in the same pattern.
type fxDMRule struct {
	pattern int
	context string
	steps   []fxDMStep
	asserts []fxDMAssert
}

// ---------------------------------------------------------------------------
// The context index
// ---------------------------------------------------------------------------

// fxDMIndex is the profile's rules arranged as a trie over the step names of
// their contexts, so that one walk of the document reaches every context node and
// descends into no subtree that can hold one.
//
// It is a trie rather than a list of paths because the alternative is 903 root-to-
// context descents per document for EXTENDED, each rescanning the same children.
// The trie makes the walk O(nodes in the document that lie on some context path),
// which for a real invoice is a small fraction of the tree: a walk that meets a
// child whose name no rule mentions stops there.
type fxDMIndex struct {
	kids map[string]*fxDMIndex
	// rules are the indices, in artefact order, of the rules whose context step
	// names end at this node. Their predicates still have to be evaluated: two
	// rules reach the same trie node exactly when they differ only in predicate.
	rules []int
}

func (ix *fxDMIndex) insert(steps []fxDMStep, ri int) {
	cur := ix
	for _, s := range steps {
		if cur.kids == nil {
			cur.kids = map[string]*fxDMIndex{}
		}
		next := cur.kids[s.name]
		if next == nil {
			next = &fxDMIndex{}
			cur.kids[s.name] = next
		}
		cur = next
	}
	cur.rules = append(cur.rules, ri)
}

// fxDMIndexes builds one trie per profile, once per process.
//
// It is built here rather than emitted by the generator because a map literal of
// this size is a large amount of generated code to read for a structure that is
// mechanically derivable from the one above it, and because building it costs
// about a millisecond across all five profiles — paid once, against a package
// whose callers validate documents in the thousands.
var fxDMIndexes = sync.OnceValue(func() map[Profile]*fxDMIndex {
	out := make(map[Profile]*fxDMIndex, len(facturXDataModel))
	for p, rules := range facturXDataModel {
		ix := &fxDMIndex{}
		for i, r := range rules {
			fxDMCheckRule(p, &rules[i])
			ix.insert(r.steps, i)
		}
		out[p] = ix
	}
	return out
})

// fxDMCheckRule rejects a table row this build cannot read, before any document
// is read.
//
// It panics, and that is deliberate. The alternative to failing here is dropping
// the row, and a dropped row is a fatal assertion that is present in the table,
// counted by the coverage machinery and never evaluated — the C41 failure mode,
// which the guards that check "every identifier has an implementation" and "every
// context is reached" both pass. The only way to reach it is to hand-edit
// facturx_datamodel_table.go, which the generated header says not to do: it is a
// build-time fault in this package, not anything a caller's document can cause,
// and no input reaches this function.
func fxDMCheckRule(p Profile, r *fxDMRule) {
	bad := func(what string) {
		panic("formalis: facturx_datamodel_table.go is not readable by this build: the " +
			string(p) + " rule at " + r.context + " " + what +
			". Regenerate it with `make facturx-datamodel`")
	}
	// Every context in these files is an absolute path from the document element,
	// which is what makes one trie rooted there correct. An empty step list would
	// attach the rule to the root and fire its assertions on every document.
	if len(r.steps) == 0 {
		bad("has no context steps")
	}
	for i := range r.asserts {
		a := &r.asserts[i]
		if a.key == "" {
			bad("carries an assertion with no key")
		}
		switch a.op {
		case fxDMCountEQ, fxDMCountLE, fxDMCountGE:
			if a.child.name == "" {
				bad("carries the cardinality assertion " + a.key + " with no counted element")
			}
		case fxDMAttrRequired, fxDMAttrForbidden:
			if a.attr == "" {
				bad("carries the attribute assertion " + a.key + " with no attribute name")
			}
		case fxDMCode:
			if a.list < 0 || a.list >= len(facturXCodeLists) || len(facturXCodeLists[a.list]) == 0 {
				bad("carries the code-list assertion " + a.key + " pointing at no code list")
			}
		case fxDMUnused:
		default:
			bad("carries the assertion " + a.key + " with an op this build does not implement")
		}
	}
}

